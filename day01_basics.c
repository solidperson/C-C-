#include <stdio.h>

/* ================================================================
 * 知识点 1：变量与数据类型
 * ----------------------------------------------------------------
 * 是什么：变量就是一块有名有姓的内存，用来存数据。
 *         int 存整数，double 存小数，char 存单个字符。
 *
 * 为什么要管：C 是你自己管内存的语言，类型决定了这块内存多大、
 *            能存什么范围的值。选错类型，轻则精度丢失，重则溢出。
 *
 * 常见的坑：
 *   1. char 用单引号 'A'，字符串才用双引号 "A"，两者类型完全不同
 *   2. 小数默认是 double，不是 float
 *   3. 不同类型混算会隐式转换，可能悄悄丢精度
 * ================================================================ */
static void lesson1_variables(void)
{
    int    age   = 18;        /* 整数，一般 4 字节 */
    double pi    = 3.14159;   /* 双精度小数，8 字节 */
    char   grade = 'A';       /* 单个字符，1 字节；单引号！ */

    printf("[1] 变量与类型\n");
    printf("    age = %d, pi = %.2f, grade = %c\n", age, pi, grade);
    printf("    各类占用：int %zu 字节, double %zu 字节, char %zu 字节\n",
           sizeof(age), sizeof(pi), sizeof(grade));
}

/* ================================================================
 * 知识点 2：printf 与占位符
 * ----------------------------------------------------------------
 * 是什么：printf 负责把变量的值打印到屏幕上，靠占位符告诉它"按什么格式打"。
 *
 * 为什么要管：占位符和类型不匹配时，编译器不报错，但打印出来是乱值
 *            —— 这是新手最常见的"明明代码没错，结果却是垃圾"的原因。
 *
 * 占位符对照表（必须背）：
 *   %d   int
 *   %u   无符号 int
 *   %f   double（%.2f 保留两位小数）
 *   %c   char
 *   %s   字符串
 *   %p   指针（地址）
 *   %zu  size_t（sizeof 的返回值类型）
 *   %%   一个百分号本身
 * ================================================================ */
static void lesson2_printf(void)
{
    int    n = 42;
    double d = 3.14159;
    char   c = 'Z';

    printf("[2] printf 与占位符\n");
    printf("    整数：%d\n", n);
    printf("    小数：%f（默认 6 位）\n", d);
    printf("    小数：%.2f（保留 2 位，会四舍五入）\n", d);
    printf("    字符：%c\n", c);
    printf("    百分号：100%%\n");
}

/* ================================================================
 * 知识点 3：数组
 * ----------------------------------------------------------------
 * 是什么：一组同类型的连续内存，用同一个名字加下标访问。
 *
 * 为什么要管：数组是最基本的批量数据容器，后面链表、缓冲区都是在它之上做的。
 *
 * 常见的坑：
 *   1. 下标从 0 开始，最后一个元素是 arr[n-1]，不是 arr[n]
 *   2. C 不检查越界！arr[5] 能编译、能运行，读到的是垃圾内存
 *   3. 数组名本身代表首元素地址，不是"整个数组"
 * ================================================================ */
static void lesson3_array(void)
{
    int nums[5] = {4, 8, 15, 16, 23};
    int i;

    printf("[3] 数组\n");
    printf("    第 1 个元素 nums[0] = %d\n", nums[0]);
    printf("    最后 1 个元素 nums[4] = %d\n", nums[4]);
    printf("    逐个打印：");

    /* for 循环遍历数组的标准写法：从 0 到 n-1 */
    for (i = 0; i < 5; i++) {
        printf("%d ", nums[i]);
    }
    printf("\n");
}

/* ================================================================
 * 知识点 4：for 循环
 * ----------------------------------------------------------------
 * 是什么：让一段代码重复执行固定次数（或按条件重复）。
 *   语法：for (初始化; 继续条件; 每轮结束后的动作)
 *
 * 为什么要管：遍历数组、累加、扫描寄存器，全是 for 循环。
 *
 * 常见错误：
 *   1. 条件写成 i <= n，多跑一轮，越界
 *   2. 忘了 i++，死循环
 *   3. 循环变量在循环外没声明（老标准不允许，C99 之后可以写在括号里）
 * ================================================================ */
static void lesson4_for(void)
{
    int i;
    int total = 0;

    printf("[4] for 循环（1 到 5 累加）\n");

    for (i = 1; i <= 5; i++) {
        total += i;                  /* 等价于 total = total + i */
        printf("    第 %d 轮：total = %d\n", i, total);
    }
    printf("    结果：1+2+3+4+5 = %d\n", total);
}

/* ================================================================
 * 知识点 5：函数
 * ----------------------------------------------------------------
 * 是什么：把一段可以复用的逻辑起个名字包起来，需要时调用。
 *   语法：返回类型 函数名(参数列表) { 函数体 }
 *
 * 为什么要管：函数是工程化的第一步。单片机代码全是
 *           "init_gpio() / read_sensor() / send_data()" 这样的函数调用。
 *
 * 最常见的坑 —— 数组传参：
 *   数组一进函数就"退化"成一个指针，函数里 sizeof(arr) 永远是 8，
 *   拿不到真实长度。所以调用方必须把长度也传进来。
 * ================================================================ */

/* 把数组里所有元素加起来，返回总和 */
int sum_array(const int arr[], int n)
{
    int i;
    int total = 0;

    for (i = 0; i < n; i++) {
        total += arr[i];
    }
    return total;
}

static void lesson5_function(void)
{
    int nums[5] = {4, 8, 15, 16, 23};

    printf("[5] 函数\n");
    printf("    调用 sum_array(nums, 5) = %d\n", sum_array(nums, 5));
    printf("    数组名传进去只是首地址，所以长度必须另外传\n");
}

/* ================================================================
 * 知识点 6：while 循环与 if / else 分支
 * ----------------------------------------------------------------
 * 是什么：
 *   while (条件) {}  —— 条件成立就重复，次数不确定时用它
 *   if / else if / else —— 根据条件走不同的分支
 *
 * 为什么要管：所有"等硬件状态""按状态切换行为"的逻辑都是这两样。
 *
 * 常见错误：
 *   1. while 里没有能改变条件的语句 → 死循环
 *   2. if (a = 5) 写成了赋值，不是判断，条件永远为真（经典事故）
 *   3. switch 忘了 break，会继续往下执行（穿透）
 * ================================================================ */
static void lesson6_loop_branch(void)
{
    int n = 100;
    int count = 0;
    int score = 87;

    printf("[6] while 与 if/else\n");

    /* 考拉兹猜想：偶数除以 2，奇数乘 3 加 1，最终一定回到 1 */
    while (n != 1) {
        if (n % 2 == 0) {
            n = n / 2;
        } else {
            n = 3 * n + 1;
        }
        count++;
    }
    printf("    从 100 回到 1 用了 %d 步\n", count);

    /* 分数分档：注意判断顺序，先判大再判小 */
    if (score >= 90) {
        printf("    87 分判定：优秀\n");
    } else if (score >= 80) {
        printf("    87 分判定：良好\n");
    } else if (score >= 60) {
        printf("    87 分判定：及格\n");
    } else {
        printf("    87 分判定：不及格\n");
    }
}

/* ================================================================
 * 知识点 7：指针初体验
 * ----------------------------------------------------------------
 * 是什么：指针是"存地址的变量"。
 *   &x  取出 x 的地址
 *   *p  顺着 p 里存的地址，去读/写那块内存
 *
 * 为什么要管：这是嵌入式的地基 —— 寄存器就是固定地址，
 *           所以所有硬件操作本质都是"往某个地址写值"。
 *
 * 常见错误：
 *   1. p 和 *p 分不清：p 是地址，*p 是内容
 *   2. 指针没初始化就解引用 → 野指针，访问随机内存，直接崩溃
 *   3. 指针类型和指向的数据类型不匹配
 * ================================================================ */
static void lesson7_pointer(void)
{
    int  x = 42;
    int *p = &x;      /* p 存的是 x 的地址，类型是 int* */

    printf("[7] 指针\n");
    printf("    x 的值      = %d\n", x);
    printf("    x 的地址    = %p\n", (void *)p);
    printf("    通过 *p 读值 = %d\n", *p);

    *p = 99;          /* 通过指针改 x */
    printf("    通过 *p 改成 99 后，x = %d\n", x);
}

int main(void)
{
    printf("===== Day 1：C 语言基础语法 =====\n\n");

    lesson1_variables();
    printf("\n");
    lesson2_printf();
    printf("\n");
    lesson3_array();
    printf("\n");
    lesson4_for();
    printf("\n");
    lesson5_function();
    printf("\n");
    lesson6_loop_branch();
    printf("\n");
    lesson7_pointer();

    printf("\n===== 七个知识点结束 =====\n");
    return 0;
}
