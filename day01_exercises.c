/* ==================================================================
 * 第 2 题：数组统计（练数组 + 循环 + 函数）
 * ----------------------------------------------------------------
 * 数组 scores 有 5 个成绩：{78, 92, 65, 88, 95}
 *
 * 要求：
 *   1. 写一个函数 average(const int arr[], int n)，返回平均分（double）
 *   2. 写一个函数 max_value(const int arr[], int n)，返回最高分（int）
 *   3. 在 ex2_scores 里调用它们，打印：
 *      "平均分 = 83.60, 最高分 = 95"
 *
 * 提示：
 *   - 求和时累加器要从 0 开始
 *   - 算平均要先把和转成 double，否则 418/5 会变成 83 而不是 83.6
 *   - 找最大值时，初始值设成 arr[0]，然后从第 2 个元素开始比
 * ================================================================== */

/* TODO：在这里实现 average 函数 */
double average(const int arr[], int n)
{
    (void)arr;
    (void)n;
    int i;
    double sum = 0;
    for(i=0;i<n;i++)
    {
        sum += arr[i];
    }
    return sum/n;
}

