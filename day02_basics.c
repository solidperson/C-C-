#include <stdio.h>
#include <stdint.h>

/* ================================================================
 * 知识点 1：算术运算符与优先级
 * ----------------------------------------------------------------
 * 是什么：+ - * / % 这五个，加上括号。
 *
 * 为什么要管：优先级决定先算哪一步。写错括号，结果差好几倍，
 *            而且编译器不会报错 —— 只是算错了。
 *
 * 常见的坑：
 *   1. 乘除优先级高于加减，别凭感觉
 *   2. 同优先级从左往右算，所以 10 - 4 - 3 = 3（不是 9）
 *   3. 拿不准就加括号，括号不要钱
 * ================================================================ */
static void lesson1_arithmetic(void)
{
    int a = 2 + 3 * 4;        /* 先乘后加 = 14 */
    int b = (2 + 3) * 4;      /* 括号优先 = 20 */
    int c = 10 - 4 - 3;       /* 从左往右 = 3 */
    double d = 7 / 2.0;       /* 一侧是小数 → 小数除法 = 3.5 */

    printf("[1] 算术运算符与优先级\n");
    printf("    2 + 3 * 4   = %d\n", a);
    printf("    (2 + 3) * 4 = %d\n", b);
    printf("    10 - 4 - 3  = %d\n", c);
    printf("    7 / 2.0     = %.1f\n", d);
}

/* ================================================================
 * 知识点 2：整数除法与取余（两个必须记住的规则）
 * ----------------------------------------------------------------
 * 规则一：int / int = int，小数部分直接砍掉（不是四舍五入）
 * 规则二：% 的余数符号跟着"被除数"走，不是跟着除数
 *
 * 为什么要管：定时器分频、ADC 采样求平均、坐标换算，
 *            全都靠这两个运算。算错一格，硬件行为就全偏。
 *
 * 常见的坑：
 *   1. 7 / 2 得 3，想得 3.5 必须写 7 / 2.0 或 (double)7 / 2
 *   2. -7 / 2 = -3（向零取整），不是 -4
 *   3. -7 % 2 = -1（符号跟 -7 走），所以判断奇偶请用 n % 2 != 0
 *   4. 除数为 0 会直接崩（SIGFPE），嵌入式里就是死机
 * ================================================================ */
static void lesson2_divide_mod(void)
{
    int n = 7;
    int m = -7;

    printf("[2] 整数除法与取余\n");
    printf("    7 / 2   = %d      （小数被砍掉）\n", n / 2);
    printf("    7 %% 2   = %d\n", n % 2);
    printf("    -7 / 2  = %d     （向零取整）\n", m / 2);
    printf("    -7 %% 2  = %d     （符号跟被除数走）\n", m % 2);
    printf("    所以判断奇数要写 (x %% 2 != 0)，不能写 (x %% 2 == 1)\n");
}

/* ================================================================
 * 知识点 3：复合赋值与自增自减
 * ----------------------------------------------------------------
 * 是什么：x += 5 就是 x = x + 5，其余 -= *= /= %= 同理。
 *        i++ 是"用完再加"，++i 是"先加再用"。
 *
 * 为什么要管：复合赋值写起来短，而且编译器生成的指令更少
 *            （只算一次地址）。嵌入式里省指令就是省电、省时间。
 *
 * 常见的坑：
 *   1. i++ 和 ++i 在 for 循环里效果一样，但在表达式里不一样
 *   2. int i = 5; int a = i++;   → a = 5, i = 6
 *      int i = 5; int b = ++i;   → b = 6, i = 6
 *   3. 同一个表达式里对同一变量改两次（如 i++ + i++）是未定义行为
 * ================================================================ */
static void lesson3_assign(void)
{
    int x = 10;
    int i;
    int a;
    int b;

    printf("[3] 复合赋值与自增自减\n");
    x += 5;   printf("    x += 5  → %d\n", x);      /* 15 */
    x -= 3;   printf("    x -= 3  → %d\n", x);      /* 12 */
    x *= 2;   printf("    x *= 2  → %d\n", x);      /* 24 */
    x /= 4;   printf("    x /= 4  → %d\n", x);      /* 6  */
    x %= 4;   printf("    x %%= 4  → %d\n", x);     /* 2  */

    i = 5; a = i++; printf("    a = i++ → a = %d, i = %d\n", a, i);  /* 5,6 */
    i = 5; b = ++i; printf("    b = ++i → b = %d, i = %d\n", b, i);  /* 6,6 */
}

/* ================================================================
 * 知识点 4：关系与逻辑运算符
 * ----------------------------------------------------------------
 * 关系：== != > < >= <=       （== 是判断相等，= 是赋值！）
 * 逻辑：&&（与） ||（或） !（非）
 * 三目：条件 ? 真值 : 假值
 *
 * 为什么要管：所有分支判断都靠它。C 里"0 是假，非 0 是真"。
 *
 * 常见的坑：
 *   1. if (x = 5) 是赋值，条件永远真 —— 经典事故，编译器只给警告
 *   2. && 和 || 有短路特性：左边能定结果就不算右边
 *      所以 if (p != NULL && *p > 0) 写成这样是安全的，反了就崩
 *   3. ! 只认 0/非 0，所以 !5 是 0，!0 是 1
 * ================================================================ */
static void lesson4_logic(void)
{
    int a = 5;
    int b = 0;
    int max;

    printf("[4] 关系与逻辑运算符\n");
    printf("    a == 5  → %d\n", a == 5);          /* 1 */
    printf("    b == 5  → %d\n", b == 5);          /* 0 */
    printf("    a && b  → %d     （有一个 0 就是假）\n", a && b);
    printf("    a || b  → %d     （有一个非 0 就是真）\n", a || b);
    printf("    !b      → %d\n", !b);

    /* 三目运算符：一行写完的 if/else */
    max = (a > b) ? a : b;
    printf("    (a > b) ? a : b → %d\n", max);
}

/* ================================================================
 * 知识点 5：位运算（& | ^ ~ << >>）
 * ----------------------------------------------------------------
 * 是什么：按二进制位逐个运算。
 *     &  与   两位都是 1 才是 1       —— 用来"取某几位"
 *     |  或   有一位是 1 就是 1       —— 用来"置位"
 *     ^  异或 两位不同才是 1          —— 用来"翻转位"
 *     ~  取反 0 变 1、1 变 0          —— 用来"清零"
 *     << 左移 每移 1 位 = 乘 2        —— 生成掩码
 *     >> 右移 每移 1 位 = 除 2        —— 取高位
 *
 * 为什么要管：这是嵌入式的母语。寄存器、标志位、协议帧全靠它。
 * ================================================================ */
static void lesson5_bitwise(void)
{
    uint8_t reg = 0x0F;       /* 二进制 0000 1111 */

    printf("[5] 位运算\n");
    printf("    0x0F     = 0x%02X\n", reg);
    printf("    & 0x3C   = 0x%02X   （按位与，取共同的 1）\n", (uint8_t)(reg & 0x3C));
    printf("    | 0x30   = 0x%02X   （按位或，把 1 加进去）\n", (uint8_t)(reg | 0x30));
    printf("    ^ 0xFF   = 0x%02X   （按位异或，翻转）\n", (uint8_t)(reg ^ 0xFF));
    printf("    ~0x0F    = 0x%02X   （按位取反）\n", (uint8_t)(~reg));
    printf("    1 << 3   = 0x%02X   （左移 3 位，等于 8）\n", (uint8_t)(1u << 3));
    printf("    0x80 >> 4= 0x%02X   （右移 4 位，等于 8）\n", (uint8_t)(0x80 >> 4));
}

/* ================================================================
 * 知识点 6：寄存器位操作（本课最核心，直接抄去用）
 * ----------------------------------------------------------------
 * 四件事在嵌入式里天天做：
 *   置位（把某位变 1）   reg |=  (1 << n)
 *   清零（把某位变 0）   reg &= ~(1 << n)
 *   翻转（1 变 0、0 变 1）reg ^=  (1 << n)
 *   读位（看它是 0 还是 1） (reg >> n) & 1
 *
 * 常见的坑：
 *   1. 清零写成 reg &= (1<<n) 就变成"只保留这一位"，其他位全清掉了
 *   2. 用 1 << n 而不用 1u << n，移位到 31 位时符号位出问题
 *   3. 宏参数一定要加括号：(reg) &= ~(1u << (n))
 *   4. 同时改多位要"先清后写"：reg = (reg & ~(0x3 << 4)) | (val << 4)
 * ================================================================ */

#define BIT(n)              (1u << (n))
#define SET_BIT(reg, n)     ((reg) |=  BIT(n))
#define CLEAR_BIT(reg, n)   ((reg) &= ~BIT(n))
#define TOGGLE_BIT(reg, n)  ((reg) ^=  BIT(n))
#define READ_BIT(reg, n)    (((reg) & BIT(n)) != 0u)

static void lesson6_register(void)
{
    uint8_t ctrl = 0x00;      /* 假装这是一个控制寄存器 */
    uint8_t val  = 0x03;      /* 要写进 4~5 位的值（二进制 11） */

    printf("[6] 寄存器位操作\n");
    printf("    初始            = 0x%02X\n", ctrl);

    SET_BIT(ctrl, 3);
    printf("    置位第 3 位      = 0x%02X\n", ctrl);     /* 0x08 */
    SET_BIT(ctrl, 0);
    printf("    置位第 0 位      = 0x%02X\n", ctrl);     /* 0x09 */
    CLEAR_BIT(ctrl, 3);
    printf("    清零第 3 位      = 0x%02X\n", ctrl);     /* 0x01 */
    TOGGLE_BIT(ctrl, 5);
    printf("    翻转第 5 位      = 0x%02X\n", ctrl);     /* 0x21 */
    printf("    读第 5 位        = %d\n", READ_BIT(ctrl, 5));

    /* 写一个多位的字段：先清空 4~5 位，再写入新值 */
    ctrl = (uint8_t)((ctrl & ~(0x3u << 4)) | (val << 4));
    printf("    写 4~5 位为 3    = 0x%02X\n", ctrl);     /* 0x21 → 0x31 */
}

/* ================================================================
 * 知识点 7：分支 —— if / else if / switch，以及状态机雏形
 * ----------------------------------------------------------------
 * 是什么：
 *   if / else if：按顺序比较，第一个成立的就执行，后面的全跳过
 *   switch / case：按值跳转，要 break，否则会"穿透"到下一个 case
 *
 * 为什么要管：嵌入式大量逻辑是"当前处于什么状态，收到什么事件，
 *            下一步去哪" —— 这就是状态机，写法就是 switch。
 *
 * 常见的坑：
 *   1. else if 的顺序很重要：先判大范围会吃掉小范围
 *   2. switch 忘写 break，会一直往下执行到下一个 case
 *   3. switch 的 case 只能是整型常量，不能是变量或浮点
 * ================================================================ */
typedef enum {
    STATE_IDLE = 0,      /* 待机 */
    STATE_RUN,           /* 运行 */
    STATE_FAULT          /* 故障 */
} state_t;

static const char *state_name(state_t s)
{
    switch (s) {
    case STATE_IDLE:  return "待机";
    case STATE_RUN:   return "运行";
    case STATE_FAULT: return "故障";
    default:          return "未知";
    }
}

/* 状态迁移：当前状态 + 事件 → 下一个状态 */
static state_t next_state(state_t cur, int event)
{
    switch (cur) {
    case STATE_IDLE:
        if (event == 0) {           /* 0 = 启动 */
            return STATE_RUN;
        }
        return STATE_IDLE;

    case STATE_RUN:
        if (event == 1) {           /* 1 = 停止 */
            return STATE_IDLE;
        }
        if (event == 2) {           /* 2 = 出错 */
            return STATE_FAULT;
        }
        return STATE_RUN;

    case STATE_FAULT:
        if (event == 3) {           /* 3 = 复位 */
            return STATE_IDLE;
        }
        return STATE_FAULT;

    default:
        return STATE_IDLE;
    }
}

static void lesson7_branch(void)
{
    int score = 87;

    printf("[7] 分支与状态机\n");

    /* 分支的写法：从大到小排 */
    if (score >= 90) {
        printf("    %d 分 → 优秀\n", score);
    } else if (score >= 80) {
        printf("    %d 分 → 良好\n", score);
    } else if (score >= 60) {
        printf("    %d 分 → 及格\n", score);
    } else {
        printf("    %d 分 → 不及格\n", score);
    }

    /* 状态机：一串事件驱动状态变化 */
    {
        state_t st = STATE_IDLE;
        int events[5] = {0, 2, 3, 0, 1};
        int i;

        for (i = 0; i < 5; i++) {
            st = next_state(st, events[i]);
            printf("    事件 %d → 状态：%s\n", events[i], state_name(st));
        }
    }
}

